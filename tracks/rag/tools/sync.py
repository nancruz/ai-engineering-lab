"""Regenerate the derived copies of the RAG track (maintainers only).

1. tracks/rag/starter/ from tracks/rag/solution/. Code between `# LABn-BEGIN` and
   `# LABn-END` in solution/minirag/*.py is the part a learner writes. In the
   starter, each block becomes its `# Task:` comment (as a TODO) plus
   `raise NotImplementedError(...)`. Everything else is copied unchanged.
2. docs/rag/assets/course-data.js from tracks/rag/data/ (the widgets' copy of the
   knowledge base and questions).

tests/site/test_site.py fails if either copy is out of date.

    python3 tracks/rag/tools/sync.py
"""
import json
from pathlib import Path
import re
import shutil
import sys

RAG = Path(__file__).resolve().parents[1]
SOLUTION, STARTER = RAG / "solution", RAG / "starter"
BEGIN = re.compile(r"^(\s*)# LAB(\d)-BEGIN\s*$")
END = re.compile(r"^\s*# LAB(\d)-END\s*$")
COPY = ["minirag", "tests", "Dockerfile", "requirements-optional.txt"]


def owner(lines, index):
    """Qualified name of the function enclosing line `index`."""
    func = cls = None
    for line in reversed(lines[:index]):
        if func is None and (m := re.match(r"^(\s*)def (\w+)", line)):
            func, indent = m.group(2), len(m.group(1))
            if indent == 0:
                break
            continue
        if func is not None and (m := re.match(r"^class (\w+)", line)):
            cls = m.group(1)
            break
    return f"{cls}.{func}" if cls else func


def strip_labs(source, filename):
    lines, out, i = source.splitlines(keepends=True), [], 0
    while i < len(lines):
        m = BEGIN.match(lines[i])
        if not m:
            if END.match(lines[i]):
                raise ValueError(f"{filename}:{i + 1}: LAB-END without BEGIN")
            out.append(lines[i])
            i += 1
            continue
        indent, lab = m.group(1), m.group(2)
        j = i + 1
        while j < len(lines) and not END.match(lines[j]):
            if BEGIN.match(lines[j]):
                raise ValueError(f"{filename}:{j + 1}: nested LAB-BEGIN")
            j += 1
        if j == len(lines):
            raise ValueError(f"{filename}:{i + 1}: LAB{lab}-BEGIN without END")
        body, comments = lines[i + 1:j], []
        for line in body:
            text = line.strip()
            if not text.startswith("#"):
                break
            comments.append(indent + text.replace("# Task:", f"# TODO (Lab {lab}):", 1) + "\n")
        if not comments:
            comments = [f"{indent}# TODO (Lab {lab}): implement this, following the docstring.\n"]
        where = f"{owner(lines, i)}() in minirag/{filename}"
        out += comments + [f'{indent}raise NotImplementedError("Lab {lab}: write {where}")\n']
        i = j + 1
    return "".join(out)


def build(target=STARTER):
    if target.exists():
        shutil.rmtree(target)
    for name in COPY:
        src = SOLUTION / name
        if src.is_dir():
            shutil.copytree(src, target / name, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        else:
            target.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, target / name)
    for path in sorted((target / "minirag").glob("*.py")):
        path.write_text(strip_labs(path.read_text(), path.name))
    shutil.copy2(RAG / "tools" / "STARTER_README.md", target / "README.md")


def course_data():
    """The knowledge base and questions as the browser widgets load them."""
    sys.path.insert(0, str(SOLUTION))
    from minirag.documents import load_documents, load_questions
    docs = [{"id": d.id, "title": d.title, "meta": d.meta, "body": d.body} for d in load_documents(RAG / "data" / "docs")]
    data = {"docs": docs, "questions": load_questions(RAG / "data" / "questions.json")}
    return ("/* Generated by tracks/rag/tools/sync.py from tracks/rag/data/. Do not edit by hand. */\n"
            "(function (root) { root.RAG_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + "; })"
            "(typeof window !== 'undefined' ? window : globalThis);\n")


SITE_DATA = RAG.parents[1] / "docs" / "rag" / "assets" / "course-data.js"

if __name__ == "__main__":
    build()
    SITE_DATA.write_text(course_data(), encoding="utf-8")
    print(f"wrote {STARTER.relative_to(RAG.parents[1])} and {SITE_DATA.relative_to(RAG.parents[1])}")
